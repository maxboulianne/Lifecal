// Tri alphabétique selon la langue (« Échalotes » avec les « E », etc.).
export const sortNames = (names, lang) => {
  const collator = new Intl.Collator(lang, { sensitivity: "base", numeric: true });
  return [...names].sort(collator.compare);
};

// Le catalogue dans une langue, articles triés : [{ id, icon, name, items: ["Abricots", …] }].
export function catalog(lang) {
  const k = Math.max(0, LANGS.indexOf(lang));
  const code = LANGS[k];
  return RAW.map((c) => ({ id: c.id, icon: c.icon, name: c.name[k], items: sortNames(c.items.map((i) => i[k]), code) }));
}

