// Textes français de départ, pour savoir si un texte a été modifié
let defaults = null;
function frenchDefaults() {
  if (defaults) return defaults;
  const h = emptyHouse();
  defaults = {};
  for (const t of h.tasks) {
    defaults[`task.title:${t.key}`] = t.title;
    if (t.note) defaults[`task.note:${t.key}`] = t.note;
  }
  for (const l of h.lists) {
    defaults[`list:${l.key}`] = l.title;
    for (const e of l.entries) defaults[`entry:${e.id}`] = e.text;
  }
  for (const s of h.supplies) {
    defaults[`supply.name:${s.key}`] = s.name;
    if (s.description) defaults[`supply.description:${s.key}`] = s.description;
    if (s.unit) defaults[`supply.unit:${s.key}`] = s.unit;
  }
  return defaults;
}

// Le texte dans la langue affichée : la traduction si le texte est encore celui de départ
export function houseText(field, key, stored, lang) {
  if (!key || !lang || lang === "fr") return stored;
  const id = `${field}:${key}`;
  return stored === frenchDefaults()[id] ? HOUSE_TEXTS[lang]?.[id] ?? stored : stored;
}

export const taskTitle = (task, lang) => houseText("task.title", task.key, task.title, lang);
export const taskNote = (task, lang) => houseText("task.note", task.key, task.note, lang);
export const listTitle = (list, lang) => houseText("list", list.key, list.title, lang);
export const entryText = (entry, lang) => houseText("entry", entry.id, entry.text, lang);
export const supplyName = (s, lang) => houseText("supply.name", s.key, s.name, lang);
export const supplyDescription = (s, lang) => houseText("supply.description", s.key, s.description, lang);
export const supplyUnit = (s, lang) => houseText("supply.unit", s.key, s.unit, lang);
